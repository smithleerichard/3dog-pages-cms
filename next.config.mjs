import fs from "node:fs";
import path from "node:path";

const customDir = path.join(process.cwd(), "fields", "custom");
const manifestPath = path.join(process.cwd(), "fields", "custom.generated.ts");

const listCustomFields = () => {
  if (!fs.existsSync(customDir)) return [];

  return fs
    .readdirSync(customDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) =>
      ["index.ts", "index.tsx"].some((file) =>
        fs.existsSync(path.join(customDir, name, file)),
      ),
    )
    .sort();
};

const aliasFor = (name) => {
  const alias = name.replace(/[^A-Za-z0-9_$]/g, "_");
  return /^[A-Za-z_$]/.test(alias) ? alias : `_${alias}`;
};

const generateCustomFieldsManifest = () => {
  const fields = listCustomFields();
  const imports = fields.map(
    (name) => `import * as ${aliasFor(name)}Field from "./custom/${name}";`,
  );
  const entries = fields.map(
    (name) => `  "${name}": ${aliasFor(name)}Field,`,
  );
  const source = [
    "// This file is auto-generated by next.config.mjs.",
    "// Do not edit it manually.",
    "",
    ...(imports.length ? [...imports, ""] : []),
    "export const customFields = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");

  const current = fs.existsSync(manifestPath)
    ? fs.readFileSync(manifestPath, "utf8")
    : "";

  if (current !== source) {
    fs.writeFileSync(manifestPath, source);
  }
};

generateCustomFieldsManifest();

/** @type {import('next').NextConfig} */
const nextConfig = {};

export default nextConfig;
